// Получить случайную команду по категории
export const getRandomCommand = (category: 'hotword' | 'commands' | 'negative'): RecordingCommand => {
  const commands = RECORDING_COMMANDS[category];
  const randomIndex = Math.floor(Math.random() * commands.length);
  return commands[randomIndex];
};

// Получить команду из категории, которая еще не была озвучена
export const getUnusedCommand = (
  category: 'hotword' | 'commands' | 'negative',
  usedCommandIds: Set<string>
): RecordingCommand | null => {
  const commands = RECORDING_COMMANDS[category];
  const unusedCommands = commands.filter(cmd => !usedCommandIds.has(cmd.id));
  
  if (unusedCommands.length === 0) {
    return null; // Все команды уже использованы
  }
  
  const randomIndex = Math.floor(Math.random() * unusedCommands.length);
  return unusedCommands[randomIndex];
};

// Получить случайную команду с учетом баланса (30% хотворд, 60% команды, 10% негативные)
// и отслеживанием уже озвученных команд
export const getBalancedRandomCommand = (
  currentProgress: { hotword: number; commands: number; negative: number },
  usedCommandIds?: Set<string>
): RecordingCommand => {
  const total = currentProgress.hotword + currentProgress.commands + currentProgress.negative;
  
  // Целевое распределение
  const targetRatios = {
    hotword: 0.3,
    commands: 0.6,
    negative: 0.1,
  };
  
  // Текущее распределение
  const currentRatios = {
    hotword: total > 0 ? currentProgress.hotword / total : 0,
    commands: total > 0 ? currentProgress.commands / total : 0,
    negative: total > 0 ? currentProgress.negative / total : 0,
  };
  
  // Определяем, какую категорию нужно записать
  const differences = {
    hotword: targetRatios.hotword - currentRatios.hotword,
    commands: targetRatios.commands - currentRatios.commands,
    negative: targetRatios.negative - currentRatios.negative,
  };
  
  // Выбираем категорию с наибольшим дефицитом
  const category = (Object.keys(differences) as Array<keyof typeof differences>).reduce((a, b) =>
    differences[a] > differences[b] ? a : b
  );
  
  // Если передан список использованных команд, выбираем из неиспользованных
  if (usedCommandIds && usedCommandIds.size > 0) {
    const unusedCommand = getUnusedCommand(category, usedCommandIds);
    if (unusedCommand) {
      return unusedCommand;
    }
    // Если все команды этой категории использованы, выбираем из других категорий
    const allCategories: Array<'hotword' | 'commands' | 'negative'> = ['hotword', 'commands', 'negative'];
    for (const cat of allCategories) {
      const unused = getUnusedCommand(cat, usedCommandIds);
      if (unused) {
        return unused;
      }
    }
    // Если все команды всех категорий использованы, возвращаем случайную
    // (это означает, что пользователь прошел все команды и начинаем заново)
  }
  
  return getRandomCommand(category);
};

